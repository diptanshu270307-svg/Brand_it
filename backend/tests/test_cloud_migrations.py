"""Portable migration DDL and read-only production startup regression coverage.

SQLite migrations execute against an isolated temporary database. PostgreSQL
statements are compiled, not executed; a real Cloud SQL migration smoke test is
still required before deployment.
"""
from types import SimpleNamespace

import pytest
from sqlalchemy import create_engine, event, inspect, text
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.orm import sessionmaker

from app import db as database
from app.migrations.ddl import MigrationDDL, migration_text
from app.migrations.runner import (
    get_migration_status,
    require_current_schema,
    run_migrations,
)


def test_dialect_ddl_preserves_sqlite_and_uses_postgres_identity_and_booleans():
    source = "CREATE TABLE example (id INTEGER PRIMARY KEY AUTOINCREMENT, enabled BOOLEAN NOT NULL DEFAULT 1, hidden BOOLEAN DEFAULT 0, count INTEGER DEFAULT 0, data JSON DEFAULT '{}')"
    statement = migration_text(source)
    assert str(statement.compile(dialect=sqlite.dialect())) == source
    compiled = str(statement.compile(dialect=postgresql.dialect()))
    assert "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in compiled
    assert "enabled BOOLEAN NOT NULL DEFAULT TRUE" in compiled
    assert "hidden BOOLEAN DEFAULT FALSE" in compiled
    assert "count INTEGER DEFAULT 0" in compiled
    assert "data JSON DEFAULT '{}'" in compiled
    assert "AUTOINCREMENT" not in compiled


def test_every_existing_migration_compiles_postgres_and_runs_sqlite(tmp_path):
    engine = create_engine(f"sqlite:///{tmp_path / 'portable.db'}")
    postgres_ddl = []

    @event.listens_for(engine, "before_execute")
    def capture_ddl(conn, clauseelement, multiparams, params, execution_options):
        if isinstance(clauseelement, MigrationDDL):
            postgres_ddl.append(str(clauseelement.compile(dialect=postgresql.dialect())))

    try:
        assert run_migrations(engine, target="0001") == ["0001"]
        with engine.begin() as conn:
            conn.execute(text("INSERT INTO users (email, name, password_hash) VALUES ('retained@example.test', 'Retained user', 'test-hash')"))
        assert run_migrations(engine) == ["0002", "0003", "0004", "0005"]
        assert run_migrations(engine) == []
        assert get_migration_status(engine)["is_head"] is True
        with engine.begin() as conn:
            assert conn.scalar(text("SELECT name FROM users WHERE email = 'retained@example.test'")) == "Retained user"
            conn.execute(text("INSERT INTO users (email, name, password_hash) VALUES ('next@example.test', 'Next user', 'test-hash')"))
            assert conn.scalar(text("SELECT id FROM users WHERE email = 'next@example.test'")) == 2
        assert "dimensions" in {column["name"] for column in inspect(engine).get_columns("findings")}
        assert "company_id" in {column["name"] for column in inspect(engine).get_columns("brands")}
        assert {"analysis_jobs", "workspace_usage", "revision_dependencies"} <= set(inspect(engine).get_table_names())
        assert postgres_ddl
        assert all("AUTOINCREMENT" not in sql for sql in postgres_ddl)
        assert all("BOOLEAN DEFAULT 0" not in sql and "BOOLEAN DEFAULT 1" not in sql for sql in postgres_ddl)
        created_tables = [sql for sql in postgres_ddl if "CREATE TABLE" in sql]
        assert len(created_tables) >= 20
        assert all("GENERATED BY DEFAULT AS IDENTITY" in sql for sql in created_tables)
    finally:
        engine.dispose()


def test_status_and_startup_gate_do_not_initialize_an_empty_database():
    engine = create_engine("sqlite://")
    try:
        status = get_migration_status(engine)
        assert status["current_revision"] is None
        assert not status["is_head"]
        with pytest.raises(RuntimeError, match="python backend/scripts/migrate.py upgrade"):
            require_current_schema(engine)
        assert inspect(engine).get_table_names() == []
    finally:
        engine.dispose()


def test_repeating_an_older_target_does_not_apply_later_revisions():
    engine = create_engine("sqlite://")
    try:
        run_migrations(engine, target="0001")
        assert run_migrations(engine, target="0001") == []
        assert get_migration_status(engine)["current_revision"] == "0001"
        assert "companies" not in inspect(engine).get_table_names()
        with pytest.raises(ValueError, match="Unknown migration target"):
            run_migrations(engine, target="unknown")
    finally:
        engine.dispose()


@pytest.mark.parametrize("production, configured, expected_auto", [(False, None, True), (True, None, False), (True, True, True), (False, False, False)])
def test_startup_migration_policy(monkeypatch, production, configured, expected_auto):
    from app.migrations import runner

    calls = []
    engine = create_engine("sqlite://")
    monkeypatch.setattr(database, "engine", engine)
    monkeypatch.setattr(database, "SessionLocal", sessionmaker(bind=engine))
    monkeypatch.setattr(database, "get_settings", lambda: SimpleNamespace(is_production=production, auto_migrate=configured))
    monkeypatch.setattr(runner, "run_migrations", lambda bound: calls.append("migrate"))
    monkeypatch.setattr(runner, "require_current_schema", lambda bound: calls.append("check"))
    monkeypatch.setattr(database, "migrate_existing_brands", lambda session: calls.append("backfill"))
    try:
        database.init_db()
        assert calls == (["migrate", "backfill"] if expected_auto else ["check"])
    finally:
        engine.dispose()
