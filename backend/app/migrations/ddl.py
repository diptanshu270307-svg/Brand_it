"""Compile the existing versioned DDL for the configured database dialect.

Historical migrations use two SQLite spellings: AUTOINCREMENT primary keys and
numeric Boolean defaults. Keep those statements unchanged for existing SQLite
installations, while compiling their PostgreSQL equivalents before execution.
This is deliberately limited to trusted, static migration DDL, never user SQL.
"""
import re

from sqlalchemy.ext.compiler import compiles
from sqlalchemy.sql.elements import TextClause


class MigrationDDL(TextClause):
    inherit_cache = True


def migration_text(statement: str) -> MigrationDDL:
    return MigrationDDL(statement)


@compiles(MigrationDDL, "postgresql")
def _postgresql_ddl(statement, compiler, **kwargs):
    sql = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        statement.text,
        flags=re.IGNORECASE,
    )
    sql = re.sub(
        r"\b(BOOLEAN(?:\s+NOT\s+NULL)?\s+DEFAULT)\s+([01])\b",
        lambda match: f"{match.group(1)} {'TRUE' if match.group(2) == '1' else 'FALSE'}",
        sql,
        flags=re.IGNORECASE,
    )
    return compiler.visit_textclause(TextClause(sql), **kwargs)
